# ── sitemap ──
with open(SITEMAP_PATH, 'r', encoding='utf-8') as f:
  sm = f.read()
new_blocks = ''
for p in POSTS:
  url = f'https://saju-mbti-9h1.pages.dev/blog/sinsal/{p["slug"]}.html'
  if url in sm:
    continue
  new_blocks += f'  <url>\n    <loc>{url}</loc>\n    <lastmod>2026-05-10</lastmod>\n    <changefreq>monthly</changefreq>\n    <priority>0.7</priority>\n  </url>\n'
if new_blocks:
  sm_new = sm.replace('</urlset>', new_blocks + '</urlset>')
  with open(SITEMAP_PATH, 'w', encoding='utf-8') as f:
    f.write(sm_new)
  print(f'sitemap.xml 업데이트 — 8 신살 URL 추가')

